// Copies each font's files into the crate and writes the stylesheet and the
// Rust list that embed them. Run with `mise run fonts:build`.
import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, '../src/usecase/build/fonts');
const FILES = join(OUT, 'builtins');

// [package, stylesheets, name of the license file in the output]
const FONTS = [
  ['@fontsource-variable/rubik', ['wght.css', 'wght-italic.css'], 'rubik.LICENSE'],
  ['@fontsource-variable/noto-sans-jp', ['wght.css'], 'noto-sans-jp.LICENSE'],
];

// A font drops and adds subsets between releases, so start from nothing.
rmSync(FILES, { recursive: true, force: true });
mkdirSync(FILES, { recursive: true });

let css = '';
for (const [pkg, sheets, license] of FONTS) {
  const dir = join(HERE, 'node_modules', pkg);
  for (const file of readdirSync(join(dir, 'files'))) {
    if (file.endsWith('.woff2')) copyFileSync(join(dir, 'files', file), join(FILES, file));
  }
  copyFileSync(join(dir, 'LICENSE'), join(FILES, license));
  for (const sheet of sheets) {
    // The theme names the families without Fontsource's " Variable" suffix,
    // and the files sit next to the stylesheet rather than under files/.
    css += readFileSync(join(dir, sheet), 'utf8')
      .replaceAll(" Variable';", "';")
      .replaceAll('url(./files/', 'url(./');
  }
}
writeFileSync(join(FILES, 'fonts.css'), css);

const names = readdirSync(FILES).sort();
const entries = names.map((n) => `    ("${n}", include_bytes!("builtins/${n}")),`).join('\n');
writeFileSync(
  join(OUT, 'builtins.rs'),
  `// Generated by \`mise run fonts:build\` from fonts/package.json. Do not edit.
#[rustfmt::skip]
pub const BUILTINS: &[(&str, &[u8])] = &[
${entries}
];
`,
);
console.log(`✔︎ ${names.length} files`);
